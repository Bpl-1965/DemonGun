const DEFAULT_EVENT = 'onIdle';
const EVENT_TYPES = Object.keys(TAUNTS);

/** 每個情境最近講過的台詞索引，避免連續重複 */
const RECENT = new Map();
const RECENT_LIMIT = 3;

/** 把 {player} / {damage} 之類的佔位符換成實際值（沒給就原樣保留） */
function format(line, vars) {
  if (!vars || typeof vars !== 'object') return line;
  return String(line).replace(/\{([A-Za-z_]+)\}/g, (whole, key) => {
    const value = vars[key];
    return value === undefined || value === null ? whole : String(value);
  });
}

/** 這個情境有沒有台詞 */
function hasTaunt(eventType) {
  return Array.isArray(TAUNTS[eventType]) && TAUNTS[eventType].length > 0;
}

/** 列出所有情境（除錯 / 前端圖鑑用） */
function listEvents() {
  return EVENT_TYPES.slice();
}

/**
 * 依情境隨機抽一句台詞。
 *
 * @param {string} eventType  情境鍵（onPlayerShootDemon / onDemonShoot / onEmptyGun …）
 * @param {object} [options]
 * @param {function} [options.rng]     亂數來源（預設 Math.random，測試可注入）
 * @param {number}  [options.chance]   開口機率 0~1（預設 1）；沒過就回 null
 * @param {object}  [options.vars]     變數插值表
 * @param {boolean} [options.avoidRepeat] 是否避開最近講過的幾句（預設 true）
 * @returns {string|null} 台詞，或 null（這個情境不說話 / 機率沒過）
 */
function getTaunt(eventType, options = {}) {
  const pool = TAUNTS[eventType];
  if (!Array.isArray(pool) || pool.length === 0) {
    // 未知情境：退回通用台詞，而不是讓呼叫端拿到 undefined
    if (eventType && eventType !== DEFAULT_EVENT) return getTaunt(DEFAULT_EVENT, options);
    return null;
  }

  const rng = typeof options.rng === 'function' ? options.rng : Math.random;
  const chance = typeof options.chance === 'number' ? options.chance : 1;
  if (chance <= 0) return null;
  if (chance < 1 && rng() > chance) return null;

  const avoidRepeat = options.avoidRepeat !== false;
  const recent = avoidRepeat ? RECENT.get(eventType) || [] : [];
  let candidates = pool.map((_, index) => index).filter((index) => !recent.includes(index));
  if (candidates.length === 0) candidates = pool.map((_, index) => index); // 全都講過了就重來

  const pick = candidates[Math.min(candidates.length - 1, Math.floor(rng() * candidates.length))];
  const line = pool[pick];

  if (avoidRepeat) {
    const next = recent.concat(pick).slice(-Math.min(RECENT_LIMIT, pool.length - 1 || 1));
    RECENT.set(eventType, next);
  }

  return format(line, options.vars);
}

/** 清掉「最近講過」的紀錄（測試 / 重開新局時用） */
function resetRecent() {
  RECENT.clear();
}

module.exports = {
  TAUNTS,
  EVENT_TYPES,
  DEFAULT_EVENT,
  getTaunt,
  hasTaunt,
  listEvents,
  format,
  resetRecent,
};
